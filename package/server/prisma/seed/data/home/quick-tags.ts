const chipColors = [
  'default',
  'primary',
  'secondary',
  'error',
  'info',
  'success',
  'warning',
];

type QuickTag = {
  icon: string;
  name: string;
  color: (typeof chipColors)[number];
};

function getRandomItem<T>(arr: T[]): T {
  const index = Math.floor(Math.random() * arr.length);
  const item = arr[index];
  if (!item) {
    throw new Error('Item is undefined');
  }
  return item;
}

export function generateQuickTags(count: number = 20): QuickTag[] {
  const shuffledTags = [...novelTags].sort(() => Math.random() - 0.5);
  const shuffledIcons = [...techIcons].sort(() => Math.random() - 0.5);

  const result = Array.from({length: count}, (_, index) => ({
    icon: shuffledIcons[index % shuffledIcons.length],
    name: shuffledTags[index % shuffledTags.length],
    color: getRandomItem(chipColors),
  }));
  return result as QuickTag[];
}

