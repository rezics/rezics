import { lstatSync, readdirSync, rmSync } from "node:fs";
import { join } from "node:path";

const targetDir = process.argv[2] || process.cwd();

let deletedCount = 0;

function removeNodeModules(dir: string): void {
  try {
    const files = readdirSync(dir);

    for (const file of files) {
      const fullPath = join(dir, file);
      const stats = lstatSync(fullPath);

      if (stats.isDirectory()) {
        if (file === "node_modules") {
          console.log(`Removing: ${fullPath}`);
          rmSync(fullPath, { recursive: true, force: true });
          deletedCount++;
        } else {
          // Recursively search subdirectories
          removeNodeModules(fullPath);
        }
      }
    }
  } catch (error) {
    if (error instanceof Error) {
      console.error(`Error accessing directory ${dir}: ${error.message}`);
    }
  }
}

console.log(`Searching for node_modules in directory: ${targetDir}`);
removeNodeModules(targetDir);
console.log(
  `Cleanup complete. Removed ${deletedCount} node_modules directories.`,
);
