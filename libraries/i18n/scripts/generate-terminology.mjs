import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { terminologyConcepts } from "@rezics/i18n/terminology/concepts";
import { deTerminology } from "@rezics/i18n/terminology/de";
import { enTerminology } from "@rezics/i18n/terminology/en";
import { jaTerminology } from "@rezics/i18n/terminology/ja";
import { koTerminology } from "@rezics/i18n/terminology/ko";
import { zhHansTerminology } from "@rezics/i18n/terminology/zh-Hans";
import { zhHantTerminology } from "@rezics/i18n/terminology/zh-Hant";

const packageRoot = fileURLToPath(new URL("..", import.meta.url));
const generatedRoot = resolve(packageRoot, "generated");
const terminologyByLocale = {
	en: enTerminology,
	"zh-Hant": zhHantTerminology,
	"zh-Hans": zhHansTerminology,
	de: deTerminology,
	ja: jaTerminology,
	ko: koTerminology,
};

function escapeMarkdown(value) {
	return value.replaceAll("|", "\\|").replaceAll("\n", " ");
}

function escapeTsv(value) {
	return value.replaceAll("\t", " ").replaceAll("\r", " ").replaceAll("\n", " ");
}

function renderMarkdown() {
	const lines = [
		"# REZICS terminology",
		"",
		"<!-- Generated by libraries/i18n/scripts/generate-terminology.mjs. Do not edit. -->",
		"",
		"This document is a generated view of the typed termbase in `libraries/i18n/src/terminology`. Product locale resources remain the owner of complete user-visible messages.",
		"",
	];
	for (const [concept, definition] of Object.entries(terminologyConcepts)) {
		lines.push(`## ${concept}`, "", definition.definition, "");
		lines.push(
			"| Locale | Status | Slot | Approved form | Forbidden forms |",
			"| --- | --- | --- | --- | --- |",
		);
		for (const [locale, terminology] of Object.entries(terminologyByLocale)) {
			const entry = terminology[concept];
			if (!entry) continue;
			for (const [slot, value] of Object.entries(entry.forms)) {
				lines.push(
					`| ${locale} | ${entry.status} | ${slot} | ${escapeMarkdown(value)} | ${escapeMarkdown(entry.forbidden.join(", "))} |`,
				);
			}
		}
		lines.push("");
	}
	return `${lines.join("\n").trimEnd()}\n`;
}

function renderTsv() {
	const lines = ["concept\tdefinition\tlocale\tstatus\tslot\tapproved_form\tforbidden_forms"];
	for (const [concept, definition] of Object.entries(terminologyConcepts)) {
		for (const [locale, terminology] of Object.entries(terminologyByLocale)) {
			const entry = terminology[concept];
			if (!entry) continue;
			for (const [slot, value] of Object.entries(entry.forms)) {
				lines.push(
					[
						concept,
						definition.definition,
						locale,
						entry.status,
						slot,
						value,
						entry.forbidden.join(" | ") || "-",
					]
						.map(escapeTsv)
						.join("\t"),
				);
			}
		}
	}
	return `${lines.join("\n")}\n`;
}

const outputs = new Map([
	[resolve(generatedRoot, "terminology.md"), renderMarkdown()],
	[resolve(generatedRoot, "terminology.tsv"), renderTsv()],
]);

if (process.argv.includes("--check")) {
	const errors = [];
	for (const [path, expected] of outputs) {
		let actual;
		try {
			actual = await readFile(path, "utf8");
		} catch {
			errors.push(`${path} is missing; run the terminology generator`);
			continue;
		}
		if (actual !== expected) errors.push(`${path} is stale; run the terminology generator`);
	}
	if (errors.length > 0) {
		console.error(errors.join("\n"));
		process.exitCode = 1;
	}
} else {
	await mkdir(generatedRoot, { recursive: true });
	await Promise.all([...outputs].map(([path, content]) => writeFile(path, content)));
}
